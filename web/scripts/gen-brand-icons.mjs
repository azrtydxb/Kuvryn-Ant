// Generates src/brandIcons.ts: only the Simple Icons (CC0, pinned in
// package.json) that the upstream catalog uses, so the embedded console stays
// small and never loads icons from a CDN. Run with `npm run generate:icons`.
// Each icon carries a fill per theme, nudged until it keeps 3:1 against the
// icon tile, so dark logos (GitHub) and light ones stay legible in both themes.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as si from "simple-icons";

const slugs = [
  "docker",
  "github",
  "googlecloud",
  "google",
  "kubernetes",
  "gitlab",
  "nvidia",
  "npm",
  "pypi",
  "apachemaven",
  "gradle",
  "go",
  "rust",
  "nuget",
  "helm",
  "artifacthub",
  "prometheus",
  "grafana",
  "rubygems",
  "packagist",
  "anaconda",
  "condaforge",
  "conan",
  "r",
  "dart",
  "cocoapods",
  "swift",
  "terraform",
  "ansible",
  "debian",
  "ubuntu",
  "fedora",
  "rockylinux",
  "almalinux",
  "centos",
  "alpinelinux",
  "huggingface",
  "eclipseide",
];
// Tile backgrounds: --az-raised in the dark and light design-system themes.
const tiles = { dark: "#151c29", light: "#eef1f5" };
const channel = (v) => {
  const s = v / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
const rgb = (hex) => [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16));
const lum = (hex) => {
  const [r, g, b] = rgb(hex).map(channel);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a, b) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};
const mix = (hex, toward, t) =>
  rgb(hex)
    .map((v, i) => Math.round(v + (rgb(toward)[i] - v) * t))
    .map((v) => v.toString(16).padStart(2, "0"))
    .join("");
function fit(hex, bg, toward) {
  for (let t = 0; t <= 1.0001; t += 0.05) {
    const c = mix(hex, toward, t);
    if (contrast(c, bg) >= 3) return c;
  }
  return toward;
}
const all = Object.values(si).filter(
  (v) => v && typeof v === "object" && v.slug,
);
const bySlug = new Map(all.map((i) => [i.slug, i]));
const out = {};
for (const slug of slugs) {
  const icon = bySlug.get(slug);
  if (!icon) throw new Error(`simple-icons has no "${slug}" icon`);
  out[slug] = {
    title: icon.title,
    path: icon.path,
    dark: fit(icon.hex, tiles.dark.slice(1), "ffffff"),
    light: fit(icon.hex, tiles.light.slice(1), "000000"),
  };
}
const version = JSON.parse(
  readFileSync(
    fileURLToPath(
      new URL("../node_modules/simple-icons/package.json", import.meta.url),
    ),
    "utf8",
  ),
).version;
const body = Object.entries(out)
  .map(
    ([slug, i]) =>
      `  ${slug}: {\n    title: ${JSON.stringify(i.title)},\n    dark: "#${i.dark}",\n    light: "#${i.light}",\n    path: ${JSON.stringify(i.path)},\n  },`,
  )
  .join("\n");
writeFileSync(
  fileURLToPath(new URL("../src/brandIcons.ts", import.meta.url)),
  `// Generated by scripts/gen-brand-icons.mjs from Simple Icons ${version} (CC0-1.0).
// Do not edit by hand. Logos are trademarks of their owners and are used here
// only to identify the upstream a source points at; see THIRD_PARTY_NOTICES.
export type BrandIcon = {
  title: string;
  /** Fill on the dark theme tile (3:1 or better). */
  dark: string;
  /** Fill on the light theme tile (3:1 or better). */
  light: string;
  /** SVG path on a 24x24 viewBox. */
  path: string;
};
export const brandIcons = {
${body}
} as const satisfies Record<string, BrandIcon>;
export type BrandSlug = keyof typeof brandIcons;
export const SIMPLE_ICONS_VERSION = ${JSON.stringify(version)};
`,
);
console.log(`wrote ${slugs.length} icons from simple-icons ${version}`);
